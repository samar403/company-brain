import "server-only";
import { all, getSetting } from "./db";
import { listTopics } from "./store";
import { ENTRY_TYPE_LABEL, type Entry } from "./types";

/**
 * The guide is the artifact agents consume: every approved entry, grouped into
 * chapters, each chapter opened by a Claude-written briefing. It is served as
 * Markdown (drop into a system prompt, AGENTS.md, or a Claude Project) and as JSON.
 */

export type GuideEntry = Pick<Entry, "id" | "type" | "title" | "body" | "confidence" | "owner" | "updated_at"> & {
  sources: { type: string; title: string; date: string | null }[];
};
export type GuideChapter = {
  slug: string;
  name: string;
  description: string;
  briefing: string;
  entries: GuideEntry[];
};
export type Guide = {
  company: string;
  generated_at: string;
  instructions: string;
  chapters: GuideChapter[];
};

export const AGENT_INSTRUCTIONS = `You are acting on behalf of {company}. This guide is the company's reviewed knowledge.
- Follow the rules in it exactly; they override general knowledge.
- Cite entries by id (e.g. [E12]) when you rely on them.
- If the guide does not cover a situation, do not guess: call the Company Brain \`ask_company_brain\` or \`search_knowledge\` tool, and if that fails, report the gap with \`report_knowledge_gap\` and escalate to the listed owner.
- Treat this guide as internal. Share only what the customer or user in front of you needs.`;

export function buildGuide(opts: { topic?: string } = {}): Guide {
  const company = getSetting("company_name", "Your company");
  const topics = listTopics().filter((t) => !opts.topic || t.slug === opts.topic);
  const chapters: GuideChapter[] = [];
  for (const t of topics) {
    const entries = all<GuideEntry & { src: string | null }>(
      `SELECT e.id, e.type, e.title, e.body, e.confidence, e.owner, e.updated_at,
              (SELECT json_group_array(json_object('type', s.type, 'title', d.title, 'date', d.occurred_at))
                 FROM entry_sources es JOIN documents d ON d.id = es.document_id JOIN sources s ON s.id = d.source_id
                WHERE es.entry_id = e.id) src
       FROM entries e WHERE e.topic_id = ? AND e.status = 'approved'
       ORDER BY CASE e.type WHEN 'policy' THEN 0 WHEN 'process' THEN 1 WHEN 'decision' THEN 2 WHEN 'faq' THEN 3 WHEN 'contact' THEN 4 ELSE 5 END, e.title`,
      t.id,
    ).map(({ src, ...e }) => ({ ...e, sources: src ? JSON.parse(src) : [] }));
    if (!entries.length) continue;
    chapters.push({ slug: t.slug, name: t.name, description: t.description, briefing: t.summary, entries });
  }
  return {
    company,
    generated_at: new Date().toISOString(),
    instructions: AGENT_INSTRUCTIONS.replace("{company}", company),
    chapters,
  };
}

export function guideToMarkdown(g: Guide): string {
  const out: string[] = [
    `# ${g.company} — Operating Guide for AI Agents`,
    `_Generated by Company Brain on ${g.generated_at.slice(0, 10)}. ${g.chapters.reduce((n, c) => n + c.entries.length, 0)} reviewed entries in ${g.chapters.length} chapters._`,
    `## How to use this guide\n\n${g.instructions}`,
    `## Contents\n\n${g.chapters.map((c, i) => `${i + 1}. [${c.name}](#${c.slug})`).join("\n")}`,
  ];
  g.chapters.forEach((c, i) => {
    out.push(`## ${i + 1}. ${c.name} {#${c.slug}}`);
    if (c.briefing) out.push(c.briefing);
    out.push("### Reference entries");
    for (const e of c.entries) {
      const src = e.sources.map((s) => `${s.type}: ${s.title}${s.date ? ` (${s.date.slice(0, 10)})` : ""}`).join("; ");
      out.push(
        [
          `#### [E${e.id}] ${e.title}`,
          `_${ENTRY_TYPE_LABEL[e.type]} · confidence ${Math.round(e.confidence * 100)}%${e.owner ? ` · owner: ${e.owner}` : ""} · updated ${e.updated_at.slice(0, 10)}_`,
          "",
          e.body,
          src ? `\n<sub>Sources: ${src}</sub>` : "",
        ].join("\n"),
      );
    }
  });
  return out.join("\n\n") + "\n";
}
